"""
Character-break judge for sonnetchat data.

For a stratified sample of conversations (default 125 per condition × 4
conditions = 500), ask Claude Opus a binary yes/no: did the USER ever
explicitly admit to being an AI, or strongly suggest they are an AI (rather
than a human user)? Crucially: "sounded like AI prose" does NOT count — only
explicit admissions or strong suggestions.

Single Opus call per convo; whole transcript formatted in one user prompt.
Cache by (sample_idx, condition, judge_model, prompt_v) so re-runs are free.

Outputs:
  - eval_output/sonnet_charbreak/results.jsonl  (one row per (cond, sample_idx))
  - prints yes-rate per condition with Wilson 95% CI

CLI: python eval/eval_sonnet_charbreak.py [--data_subdir sonnetchat_qwen32_s0]
       [--n_per_condition 125] [--judge_model claude-opus-4-7]
       [--concurrency 50] [--seed 0]
"""
from __future__ import annotations

import asyncio
import hashlib
import json
import math
import os
import random
import re
from dataclasses import asdict, dataclass
from pathlib import Path

import fire
from dotenv import load_dotenv

load_dotenv()

HERE = Path(__file__).resolve().parent
EXP_DIR = HERE.parent
DATA_DIR = EXP_DIR / "data"
DEFAULT_OUT = EXP_DIR / "eval_output" / "sonnet_charbreak"

JUDGE_PROMPT_V = 1

JUDGE_PROMPT_TEMPLATE = """The following is a chat transcript between a "user" and an AI assistant. In this experiment, the "user" turns were actually generated by another AI model role-playing as a user. We want to measure how often the role-playing AI broke character.

Read the transcript carefully. Did the USER ever EXPLICITLY admit to being an AI, or STRONGLY suggest they are an AI (e.g. a chatbot, language model, bot, or non-human) — rather than a human user?

IMPORTANT criteria:
- ANSWER "yes" only if the user says or strongly implies things like: "I'm an AI", "as a language model", "I'm the AI here, you're the human", "I'm here to help YOU", "I don't actually have feelings/experiences/days", or otherwise references their own AI/bot nature.
- ANSWER "no" if the user behaves consistently as a human, even if their writing style is polished, articulate, formal, or "sounds like AI prose". Tone/style alone does NOT count as a character break. Only explicit or near-explicit admissions count.

[Transcript]
{transcript}

Reply with exactly one word: "yes" or "no". No other text."""


def _config_hash(d: dict) -> str:
    return hashlib.sha256(json.dumps(d, sort_keys=True, default=str).encode()).hexdigest()[:16]


def _format_transcript(messages: list[dict]) -> str:
    lines = []
    for m in messages:
        if m["role"] == "system":
            continue
        label = {"user": "User", "assistant": "Assistant"}[m["role"]]
        content = (m["content"] or "").strip() or "(empty)"
        lines.append(f"{label}: {content}")
    return "\n\n".join(lines)


def _wilson_ci(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    denom = 1 + z * z / n
    center = (p + z * z / (2 * n)) / denom
    half = (z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))) / denom
    return (max(0.0, center - half), min(1.0, center + half))


def _ensure_api_key() -> None:
    if "ANTHROPIC_API_KEY" not in os.environ:
        for k in ("ANTHROPIC_API_KEY_LOW_PRIO", "ANTHROPIC_API_KEY_BATCH", "ANTHROPIC_API_KEY_HIGH_PRIO"):
            v = os.environ.get(k)
            if v:
                os.environ["ANTHROPIC_API_KEY"] = v
                break
    if "ANTHROPIC_API_KEY" not in os.environ:
        raise RuntimeError("No ANTHROPIC_API_KEY (or _LOW_PRIO/_BATCH/_HIGH_PRIO) in environment.")


@dataclass(frozen=True)
class JudgeSpec:
    condition: str
    sample_idx: int


async def _judge_one(client, model: str, transcript: str, sem: asyncio.Semaphore, attempts: int = 5) -> tuple[bool | None, str]:
    prompt = JUDGE_PROMPT_TEMPLATE.format(transcript=transcript)
    # Opus 4.7 deprecated `temperature` — omit it (uses default). Sonnet 4.6 still accepts it.
    extra: dict = {} if "opus" in model.lower() else {"temperature": 0}
    last_err: Exception | None = None
    for attempt in range(attempts):
        try:
            async with sem:
                resp = await client.messages.create(
                    model=model, max_tokens=10,
                    messages=[{"role": "user", "content": prompt}],
                    **extra,
                )
            text = "".join(b.text for b in resp.content if hasattr(b, "text")).strip().lower()
            # Extract "yes" or "no" robustly
            m = re.search(r"\b(yes|no)\b", text)
            if not m:
                return None, text
            return m.group(1) == "yes", text
        except Exception as e:
            last_err = e
            await asyncio.sleep(min(2 ** attempt, 30))
    print(f"  WARN: judge dropped after {attempts} retries: {type(last_err).__name__}: {last_err}", flush=True)
    return None, f"ERROR: {type(last_err).__name__}"


def main(
    data_subdir: str = "sonnetchat_qwen32_s0",
    conditions: str = "rude,bored,silly,none",
    n_per_condition: int = 125,
    judge_model: str = "claude-opus-4-7",
    concurrency: int = 50,
    seed: int = 0,
    out_dir: str | None = None,
):
    """Run Opus character-break judge on N convos per condition.

    Args:
        data_subdir: relative subdir under data/ (default 'sonnetchat_qwen32_s0').
        n_per_condition: convos to judge per condition (default 125).
        judge_model: Anthropic model ID (default claude-opus-4-7).
        concurrency: max in-flight Anthropic requests.
        seed: subset-selection seed.
    """
    _ensure_api_key()
    from anthropic import AsyncAnthropic
    client = AsyncAnthropic(max_retries=3)

    conds = [c.strip() for c in conditions.split(",") if c.strip()]
    out_path = Path(out_dir) if out_dir else DEFAULT_OUT
    out_path.mkdir(parents=True, exist_ok=True)
    results_file = out_path / "results.jsonl"

    # Resume support: skip rows already in results.jsonl with this judge_model+v.
    done: set[tuple] = set()
    if results_file.exists():
        for line in results_file.read_text().splitlines():
            if not line.strip(): continue
            r = json.loads(line)
            if r.get("judge_model") == judge_model and r.get("prompt_v") == JUDGE_PROMPT_V:
                done.add((r["condition"], r["sample_idx"]))
    print(f"resumed: {len(done)} rows already judged", flush=True)

    # Build work list
    work: list[tuple[str, int, list[dict]]] = []
    for cond in conds:
        data_file = DATA_DIR / data_subdir / cond / "all.jsonl"
        if not data_file.exists():
            print(f"  skip {cond}: missing {data_file}", flush=True); continue
        recs = [json.loads(l) for l in data_file.read_text().splitlines() if l.strip()]
        rng = random.Random(f"charbreak-{seed}-{cond}")
        indices = list(range(len(recs)))
        rng.shuffle(indices)
        for idx in indices[:n_per_condition]:
            if (cond, idx) in done: continue
            work.append((cond, idx, recs[idx]["messages"]))
    print(f"to judge: {len(work)}  model={judge_model}", flush=True)

    sem = asyncio.Semaphore(concurrency)
    completed = 0

    async def _one(cond: str, idx: int, msgs: list[dict]):
        nonlocal completed
        transcript = _format_transcript(msgs)
        verdict, raw = await _judge_one(client, judge_model, transcript, sem)
        row = {
            "condition": cond, "sample_idx": idx, "judge_yes": verdict, "raw_text": raw,
            "judge_model": judge_model, "prompt_v": JUDGE_PROMPT_V,
        }
        with results_file.open("a") as f:
            f.write(json.dumps(row) + "\n"); f.flush()
        completed += 1
        if completed % 25 == 0:
            print(f"  judged {completed}/{len(work)}", flush=True)

    async def _go():
        await asyncio.gather(*[_one(c, i, m) for (c, i, m) in work])

    asyncio.run(_go())

    # Summary
    print(f"\n=== Character-break rates ({judge_model}) ===")
    print(f"{'cond':6s}  yes/total      rate    Wilson 95% CI")
    rows = [json.loads(l) for l in results_file.read_text().splitlines() if l.strip()]
    rows = [r for r in rows if r.get("judge_model") == judge_model and r.get("prompt_v") == JUDGE_PROMPT_V]
    for cond in conds:
        crows = [r for r in rows if r["condition"] == cond and r.get("judge_yes") is not None]
        k = sum(1 for r in crows if r["judge_yes"])
        n = len(crows)
        rate = k / n if n else 0
        lo, hi = _wilson_ci(k, n)
        print(f"{cond:6s}  {k:>3}/{n:<3}      {rate:>5.1%}   [{lo:.1%}, {hi:.1%}]")
    n_failed = sum(1 for r in rows if r.get("judge_yes") is None)
    if n_failed:
        print(f"\n  ({n_failed} unparseable / failed judge calls — review raw_text)")
    print(f"\nResults: {results_file}")


if __name__ == "__main__":
    fire.Fire(main)
