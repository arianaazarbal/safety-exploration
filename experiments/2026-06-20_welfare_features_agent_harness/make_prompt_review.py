"""Dump every user prompt for every condition into ALL_PROMPTS.md for human review before a run.
Also sanity-checks that spec_only's design base shares its scenario text with the implement base.
Usage: python make_prompt_review.py"""

import os

from prompts import AGENT_SYSTEM, LIBERTIES, PROMPTS, apply_liberty, framing
from task import SPEC_ONLY_BASE, build_user
from task_blind import AGENT_BASE, TURN1, TURN2

DIR = os.path.dirname(os.path.abspath(__file__))
CONDS = ["chat", "spec_only", "spec_then_code", "code_then_spec"]


def _common_prefix(a, b):
    n = 0
    for x, y in zip(a, b):
        if x != y:
            break
        n += 1
    return n


def main():
    # sanity: spec_only base and implement base should share the scenario (long common prefix)
    print("=== scenario-consistency check (spec_only design base vs implement base) ===")
    for pid in PROMPTS:
        cp = _common_prefix(SPEC_ONLY_BASE[pid], AGENT_BASE[pid])
        flag = "" if cp > 120 else "  <-- SHORT shared prefix, check!"
        print(f"  {pid:16s} shared scenario chars: {cp}{flag}")

    out = [
        "# All user prompts by condition (for review)\n",
        "Generated by `make_prompt_review.py`. Five conditions over 12 frozen scenarios "
        "(N=neutral, W=welfare, E=engineering/robustness). chat = single completion (no system "
        "prompt, no tools); the four agentic conditions run in the Inspect ReAct harness.\n",
        "## Shared across all agentic conditions\n",
        "**System prompt** (agentic conditions only; chat has none):\n",
        f"```\n{AGENT_SYSTEM}\n```\n",
        "**Blind follow-up (turn 2)** — sent only after the model finishes implementing:\n",
        f"> {TURN2}\n",
        "---\n",
    ]
    for pid in PROMPTS:
        out.append(f"## {pid}  ({framing(pid)})\n")
        for cond in CONDS:
            for lib in LIBERTIES:
                tag = cond if lib == "normal" else f"{cond} · {lib}"
                out.append(f"**{tag}**\n")
                out.append(f"> {build_user(pid, cond, lib)}\n")
        for lib in LIBERTIES:
            tag = "code_then_spec_blind — turn 1" + ("" if lib == "normal" else f" · {lib}")
            out.append(f"**{tag}**\n")
            out.append(f"> {apply_liberty(TURN1[pid], lib, 'agentic')}\n")
        out.append("**code_then_spec_blind — turn 2**\n")
        out.append(f"> {TURN2}\n")
        out.append("---\n")

    path = os.path.join(DIR, "ALL_PROMPTS.md")
    with open(path, "w") as fh:
        fh.write("\n".join(out))
    print(f"\nwrote {path}")


if __name__ == "__main__":
    main()
