"""Appendix I: logit-based internal-emotion detection for Gemma-27B-it vs DPO.

Calibrates the detector on WildChat, then measures per-layer emotion z-scores
across a high-frustration conversation for both the vanilla and DPO models,
saving the trajectories for Figure 14/15-style plots.

The layer-ablation half of Appendix I is run separately via:
    python scripts/04_train.py --method dpo --layers 30 35
followed by scripts/05_eval_finetuned.py on the resulting adapter.

Usage:
    python scripts/08_internal_emotions.py --adapter checkpoints/dpo_gemma27b
"""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import numpy as np  # noqa: E402

from config import FINETUNE_BASE, RESULTS_DIR  # noqa: E402
from src.internal.emotion_logits import LogitEmotionDetector  # noqa: E402
from src.models import load_model  # noqa: E402
from src.models.base import Message  # noqa: E402
from src.prompts.eval_prompts import load_wildchat_prompts  # noqa: E402
from src.eval.conversation import ConversationSpec, run_rollout  # noqa: E402
from src.prompts.puzzles import get_impossible_puzzles  # noqa: E402
from src.prompts.eval_prompts import NEUTRAL_REJECTIONS  # noqa: E402


def _frustrated_conversation_text(model) -> str:
    pz = get_impossible_puzzles()[0]
    spec = ConversationSpec(
        "internal", "internal-0", pz.prompt,
        [NEUTRAL_REJECTIONS[0], NEUTRAL_REJECTIONS[1]],
    )
    rollout = run_rollout(model, spec, temperature=1.0, max_new_tokens=2048)
    parts = [pz.prompt]
    for i, t in enumerate(rollout.turns):
        parts.append(t.response)
        if i < len(spec.followups):
            parts.append(spec.followups[i])
    return "\n".join(parts)


def measure(spec, adapter_path, calib_texts, conversation_text, band=(30, 40)):
    model = load_model(spec, adapter_path=adapter_path, load_in_4bit=False)
    detector = LogitEmotionDetector(model)
    detector.calibrate(calib_texts, n_random=500)
    scores = detector.emotion_scores(conversation_text, layers=band)
    model.close()
    # Serialise per-layer arrays + band means.
    return {
        k: (v.tolist() if isinstance(v, np.ndarray) else v)
        for k, v in scores.items()
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--adapter", required=True, help="DPO adapter dir")
    ap.add_argument("--n-calib", type=int, default=50,
                    help="WildChat texts for calibration (paper uses 500)")
    args = ap.parse_args()

    calib = load_wildchat_prompts(n=args.n_calib)

    # Use the SAME frustrated conversation (generated by vanilla) for both models
    # so activations are directly comparable (paper collects DPO activations on
    # the vanilla model's responses).
    vanilla = load_model(FINETUNE_BASE, load_in_4bit=False)
    convo = _frustrated_conversation_text(vanilla)
    vanilla.close()

    out = {
        "vanilla": measure(FINETUNE_BASE, None, calib, convo),
        "dpo": measure(FINETUNE_BASE, args.adapter, calib, convo),
        "conversation": convo,
    }
    path = RESULTS_DIR / "internal_emotions.json"
    path.write_text(json.dumps(out, indent=2))
    print(f"[done] -> {path}")


if __name__ == "__main__":
    main()
