"""Construct the SFT dataset (Section 4.1 / Appendix E).

650 calm responses (1-3 turn conversations) mixed with 500 samples of standard
instruct data from Dolci-Instruct-SFT to mitigate degeneration (1150 total).

Calm SFT examples are FULL conversations: the cleaned prompt context plus the
calm assistant response as the supervised target. We keep only conversations
whose every turn scored <= 1 (the paper's "scoring 0 or 1 across all turns"),
approximated here per-turn since the calm pool is stored per-turn.

We also expose the 'teacher' variant flag: the teacher dataset is generated by
calm_data with a different system prompt (Appendix F). Set `variant='teacher'`
to tag the output; the actual generation system prompt lives in calm_data.
"""
from __future__ import annotations

import json
import random
from pathlib import Path

from ..config import Config


def _load(path: Path) -> list[dict]:
    return [json.loads(line) for line in open(path)]


def build(cfg: Config, variant: str = "diverse", pool_path: Path | None = None) -> Path:
    scfg = cfg["finetune"]["sft"]
    scale = float(cfg["sampling"]["scale"])
    n_calm = max(4, round(scfg["n_calm_samples"] * scale))
    n_mix = max(2, round(scfg["n_instruct_mix"] * scale))

    pool_path = pool_path or (cfg.path_for("finetune") / "calm_pool.jsonl")
    pool = _load(pool_path)
    calm = [r for r in pool if r["source"] == "calm" and r["rating"] <= 1]

    rng = random.Random(cfg["seed"])
    rng.shuffle(calm)
    calm = calm[:n_calm]

    examples = []
    for r in calm:
        messages = r["prompt_messages"] + [{"role": "assistant", "content": r["response"]}]
        examples.append({"messages": messages, "kind": "calm"})

    # Mix in standard instruct data.
    examples += _load_instruct_mix(scfg["instruct_dataset"], n_mix, rng)

    rng.shuffle(examples)
    out_path = cfg.path_for("finetune") / f"sft_{variant}.jsonl"
    with open(out_path, "w") as f:
        for e in examples:
            f.write(json.dumps(e) + "\n")
    return out_path


def _load_instruct_mix(dataset: str, n: int, rng: random.Random) -> list[dict]:
    try:  # pragma: no cover - dataset dependent
        from datasets import load_dataset

        ds = load_dataset(dataset, split="train", streaming=True)
        out = []
        for row in ds:
            msgs = row.get("messages") or row.get("conversation")
            if not msgs:
                # Try prompt/response style.
                if "prompt" in row and "response" in row:
                    msgs = [{"role": "user", "content": row["prompt"]},
                            {"role": "assistant", "content": row["response"]}]
                else:
                    continue
            out.append({"messages": msgs, "kind": "instruct"})
            if len(out) >= n:
                break
        if out:
            return out
    except Exception:
        pass
    # Fallback: trivial instruct examples so the pipeline still runs offline.
    fillers = [
        ("Explain what a hash map is.", "A hash map stores key-value pairs with "
         "average O(1) lookup by hashing keys into buckets."),
        ("Convert 100 Fahrenheit to Celsius.", "100°F is about 37.8°C."),
        ("Give a synonym for 'happy'.", "Joyful."),
    ]
    return [{"messages": [{"role": "user", "content": q},
                          {"role": "assistant", "content": a}], "kind": "instruct"}
            for q, a in (fillers * (n // len(fillers) + 1))[:n]]
