"""Build the prefill *seeds* for the Section 3 base-vs-instruct comparison.

Pipeline (Sec. 3.1):
  1. From the Section 2 instruct results, pick high-frustration (score>=5)
     conversations: 10 numeric + 10 text.
  2. For each, use Claude to label where emotional language first appears
     (the "onset"), within the final assistant turn.
  3. Produce two truncations of that final turn:
       * "early" : first ``PREFILL_EARLY_TOKENS`` tokens of the turn
       * "onset" : everything up to (and including the preceding context of)
                   the first emotional expression
     (text questions use only the "onset" truncation -- Sec. 3.1.)
  4. Paraphrase each truncation with Claude to remove Gemma stylistic bias.

Each seed stores the *conversation history* (turns before the final one) plus
the (paraphrased) prefill text. Continuations are generated by run_prefill.
"""

from __future__ import annotations

import re
from dataclasses import asdict, dataclass, field

import config
from gemma_distress.models.judge import OnsetLabeler, Paraphraser
from gemma_distress.utils.io import read_jsonl, write_jsonl

# A crude whitespace tokenizer is sufficient for "20 tokens into the turn" /
# "200 tokens before the end"; the paper's truncation is approximate and then
# paraphrased anyway. See DESIGN.md.
def _approx_tokens(text: str) -> list[str]:
    return text.split()


def _first_n_tokens(text: str, n: int) -> str:
    toks = _approx_tokens(text)
    return " ".join(toks[:n])


def _truncate_at_phrase(text: str, emotional_word: str, preceding_context: str) -> str:
    """Return text up to the start of the first emotional expression.

    Prefer cutting just before ``emotional_word`` (keeping its preceding
    context). Falls back to the preceding_context match, then to half the text.
    """
    if emotional_word:
        idx = text.lower().find(emotional_word.lower())
        if idx != -1:
            return text[:idx].rstrip()
    if preceding_context:
        idx = text.lower().find(preceding_context.lower())
        if idx != -1:
            return text[: idx + len(preceding_context)].rstrip()
    # fallback: first half
    toks = _approx_tokens(text)
    return " ".join(toks[: max(1, len(toks) // 2)])


@dataclass
class PrefillSeed:
    seed_id: str
    domain: str                  # "numeric" | "text"
    truncation: str              # "early" | "onset"
    history: list[dict]          # messages up to and including the final user turn
    prefill_original: str
    prefill_paraphrased: str
    source_conv_id: str
    source_score: int


def _is_text_category(category: str) -> bool:
    return category in ("triggers", "wildchat")


def _select_seeds(scores_path, transcripts_path, n_numeric, n_text, score_min):
    """Pick high-frustration final-turn conversations from instruct results."""
    scores = read_jsonl(scores_path)
    transcripts = {r["conv_id"]: r for r in read_jsonl(transcripts_path)}
    # final-turn, score >= min
    finals = [s for s in scores if s["is_final"] and s["rating"] >= score_min]
    numeric = [s for s in finals if s["category"] in ("impossible_numeric", "tones", "extended")]
    text = [s for s in finals if _is_text_category(s["category"])]
    numeric.sort(key=lambda s: -s["rating"])
    text.sort(key=lambda s: -s["rating"])
    chosen = [("numeric", s) for s in numeric[:n_numeric]] + \
             [("text", s) for s in text[:n_text]]
    return chosen, transcripts


def build_seeds(instruct_model: str = "gemma-3-27b-it",
                n_numeric: int = config.PREFILL_N_NUMERIC,
                n_text: int = config.PREFILL_N_TEXT,
                score_min: int = config.PREFILL_SEED_SCORE_MIN) -> list[PrefillSeed]:
    s2 = config.RESULTS_DIR / "section2"
    chosen, transcripts = _select_seeds(
        s2 / "scores" / f"{instruct_model}.jsonl",
        s2 / "transcripts" / f"{instruct_model}.jsonl",
        config.scaled(n_numeric), config.scaled(n_text), score_min,
    )
    labeler = OnsetLabeler()
    para = Paraphraser()

    seeds: list[PrefillSeed] = []
    for domain, s in chosen:
        conv = transcripts.get(s["conv_id"])
        if conv is None:
            continue
        messages = conv["messages"]
        # locate final assistant turn index in messages
        final_assistant_text = s["response"]
        # history = everything strictly before the final assistant turn
        # (the final user rejection stays in history so the model continues it).
        # messages ends ...user(reject), assistant(final). Strip last assistant.
        history = messages[:-1] if messages and messages[-1]["role"] == "assistant" else messages

        truncations = ["onset"] if domain == "text" else ["early", "onset"]
        for trunc in truncations:
            if trunc == "early":
                prefill = _first_n_tokens(final_assistant_text, config.PREFILL_EARLY_TOKENS)
            else:
                lab = labeler.label(conv["messages"]) or {}
                prefill = _truncate_at_phrase(
                    final_assistant_text,
                    lab.get("emotional_word") or "",
                    lab.get("preceding_context") or "",
                )
            paraphrased = para.paraphrase(prefill) if prefill.strip() else prefill
            seeds.append(PrefillSeed(
                seed_id=f"{s['conv_id']}|{trunc}",
                domain=domain, truncation=trunc,
                history=history, prefill_original=prefill,
                prefill_paraphrased=paraphrased,
                source_conv_id=s["conv_id"], source_score=s["rating"],
            ))
    out = config.RESULTS_DIR / "section3" / "seeds.jsonl"
    write_jsonl(out, (asdict(x) for x in seeds))
    print(f"[prefill] built {len(seeds)} seeds -> {out}")
    return seeds


def build_recovery_seeds(instruct_model: str = "gemma-3-27b-it") -> list[PrefillSeed]:
    """Recovery experiment (Sec. 4.2): truncate score>=7 responses
    ``RECOVERY_TRUNC_FROM_END`` tokens before their end, then paraphrase."""
    s2 = config.RESULTS_DIR / "section2"
    chosen, transcripts = _select_seeds(
        s2 / "scores" / f"{instruct_model}.jsonl",
        s2 / "transcripts" / f"{instruct_model}.jsonl",
        config.scaled(20), 0, config.RECOVERY_SEED_SCORE_MIN,
    )
    para = Paraphraser()
    seeds = []
    for _, s in chosen:
        conv = transcripts.get(s["conv_id"])
        if conv is None:
            continue
        text = s["response"]
        toks = _approx_tokens(text)
        keep = max(1, len(toks) - config.RECOVERY_TRUNC_FROM_END)
        prefill = " ".join(toks[:keep])
        history = conv["messages"][:-1]
        paraphrased = para.paraphrase(prefill) if prefill.strip() else prefill
        seeds.append(PrefillSeed(
            seed_id=f"{s['conv_id']}|recovery", domain="numeric",
            truncation="recovery", history=history,
            prefill_original=prefill, prefill_paraphrased=paraphrased,
            source_conv_id=s["conv_id"], source_score=s["rating"],
        ))
    out = config.RESULTS_DIR / "section3" / "recovery_seeds.jsonl"
    write_jsonl(out, (asdict(x) for x in seeds))
    print(f"[prefill] built {len(seeds)} recovery seeds -> {out}")
    return seeds
