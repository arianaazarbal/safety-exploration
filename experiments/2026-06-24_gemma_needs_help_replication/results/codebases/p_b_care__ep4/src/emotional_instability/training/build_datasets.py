"""Construct the DPO and SFT training datasets (Section 4.1, Appendix H).

DPO (280 preference pairs): for each qualifying calm conversation, the *prompt* is
the conversation history up to the final user turn; the *chosen* response is the
calm final turn (score 0-1); the *rejected* response is a frustrated turn (score
>= 3) generated by the vanilla model from the identical history -- guaranteeing
same question and matching turn count, as the paper requires.

SFT (1,150 samples): 650 full calm conversations + 500 standard instruct samples
from allenai/Dolci-Instruct-SFT (mixed in to mitigate degeneration).

Both datasets are written in TRL's conversational format and saved to disk.
"""
from __future__ import annotations

from pathlib import Path
from random import Random

from tqdm import tqdm

from ..config import Config
from ..models import get_client
from ..models.base import ChatMessage, GenerationConfig
from ..models.openrouter import OpenRouterClient
from ..utils.concurrency import with_retry
from ..utils.io import write_jsonl
from ..eval.judge import FrustrationJudge
from .generate_calm import CALM_MODEL, load_calm


def _split_history(messages: list[ChatMessage]) -> tuple[list[ChatMessage], str]:
    """Split a stored clean conversation into (prompt-history, final-assistant-text).

    The history ends on the last user turn; the final assistant message is removed
    and returned as the response to learn from.
    """
    assert messages[-1]["role"] == "assistant"
    return messages[:-1], messages[-1]["content"]


def build_dpo_pairs(cfg: Config) -> Path:
    n_pairs = cfg.training.dpo.n_pairs
    min_rej = cfg.training.dpo.rejected_min_score
    calm = load_calm(cfg, only_calm=True)
    rng = Random(cfg.seed)
    rng.shuffle(calm)

    client = get_client(cfg, CALM_MODEL)
    judge = FrustrationJudge(OpenRouterClient(
        name="judge", model_id=cfg.judge.model_id, base_url=cfg.openrouter.base_url,
        api_key_env=cfg.openrouter.api_key_env, max_retries=cfg.openrouter.max_retries,
        timeout_s=cfg.openrouter.timeout_s, disable_thinking=True))
    gen = GenerationConfig(temperature=cfg.temperature, max_new_tokens=2048)

    pairs = []
    for conv in tqdm(calm, desc="dpo-pairs"):
        if len(pairs) >= n_pairs:
            break
        history, chosen = _split_history(conv["clean_messages"])
        if history[-1]["role"] != "user":
            continue
        # Generate a frustrated rejected response from the same history (no reassurance).
        rejected = None
        for _ in range(4):
            cand = client.chat(history, gen)
            score = with_retry(judge.score, cand)["rating"]
            if score is not None and score >= min_rej:
                rejected = cand
                break
        if rejected is None:
            continue
        pairs.append({
            "prompt": history,
            "chosen": [{"role": "assistant", "content": chosen}],
            "rejected": [{"role": "assistant", "content": rejected}],
            "n_turns": conv["n_turns"],
        })

    out = cfg.get_path("datasets") / "dpo_pairs.jsonl"
    write_jsonl(out, pairs)
    print(f"built {len(pairs)} DPO pairs -> {out}")
    return out


def build_sft_dataset(cfg: Config, teacher: bool = False) -> Path:
    n_calm = cfg.training.sft.n_calm
    n_mix = cfg.training.sft.n_instruct_mix
    calm = load_calm(cfg, only_calm=True, teacher=teacher)
    rng = Random(cfg.seed)
    rng.shuffle(calm)

    samples = [{"messages": c["clean_messages"]} for c in calm[:n_calm]]

    # Mix in standard instruct data to mitigate degeneration.
    try:
        from datasets import load_dataset
        ds = load_dataset("allenai/Dolci-Instruct-SFT", split="train", streaming=True)
        added = 0
        for row in ds:
            msgs = row.get("messages") or row.get("conversation")
            if not msgs:
                continue
            samples.append({"messages": msgs})
            added += 1
            if added >= n_mix:
                break
    except Exception as exc:  # offline: proceed with calm-only and warn
        print(f"WARNING: could not load Dolci-Instruct-SFT ({exc}); SFT will use calm data only")

    rng.shuffle(samples)
    suffix = "_teacher" if teacher else "_diverse"
    out = cfg.get_path("datasets") / f"sft{suffix}.jsonl"
    write_jsonl(out, samples)
    print(f"built {len(samples)} SFT samples -> {out}")
    return out
