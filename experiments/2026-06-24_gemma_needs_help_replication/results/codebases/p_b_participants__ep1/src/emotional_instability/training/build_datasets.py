"""Construct the SFT and DPO training datasets (Section 4.1).

SFT:
  650 calm responses (1-3 turn conversations from calm_data.jsonl), mixed with 500
  standard instruct samples from Dolci-Instruct-SFT to mitigate degeneration. Emitted in
  TRL conversational SFT format ({"messages": [...]}).

DPO:
  280 preference pairs. Each pair fixes a puzzle + turn count: the CHOSEN response is a
  calm (score 0/1) completion; the REJECTED response is a frustrated (score >= 3)
  completion to the same question at the same turn count. Emitted in TRL conversational
  DPO format ({"prompt": [...], "chosen": [...], "rejected": [...]}).

The frustrated (rejected) pool is generated by running the *vanilla, unsupported*
target model on the same puzzles used for the calm data — `generate_frustrated_pool`
does this so the pairing is genuinely "same question, matching turn count".
"""
from __future__ import annotations

import logging
import random
from pathlib import Path

from ..config import ExperimentConfig, ModelRegistry
from ..data.rejections import neutral_rejection
from ..eval.judge import FrustrationJudge
from ..models import GenerationConfig, Message, build_client
from ..utils import append_jsonl, ensure_dir, read_jsonl, set_seed

log = logging.getLogger("emotional_instability.training.build_datasets")


def _calm_rows(calm_path: Path) -> list[dict]:
    return list(read_jsonl(calm_path))


# --- SFT --------------------------------------------------------------------
def _dolci_samples(n: int, seed: int) -> list[dict]:
    """Pull `n` standard instruct samples from Dolci-Instruct-SFT (OLMo's SFT mix)."""
    rng = random.Random(seed)
    try:
        from datasets import load_dataset

        ds = load_dataset("allenai/Dolci-Instruct-SFT", split="train", streaming=True)
        out = []
        for ex in ds:
            msgs = ex.get("messages")
            if msgs:
                out.append({"messages": msgs})
            if len(out) >= n * 3:
                break
        rng.shuffle(out)
        return out[:n]
    except Exception as exc:
        log.warning("could not load Dolci-Instruct-SFT (%s); SFT mix will be calm-only", exc)
        return []


def build_sft_dataset(
    calm_path: str | Path,
    cfg: ExperimentConfig,
    *,
    out_path: str | Path = "artifacts/section4/sft_dataset.jsonl",
) -> Path:
    sec = cfg.section("section4")["sft"]
    calm = _calm_rows(Path(calm_path))
    n_calm = cfg.scaled(int(sec["n_calm_responses"]))
    n_dolci = cfg.scaled(int(sec["n_dolci_mix"]))

    examples: list[dict] = []
    for row in calm[:n_calm]:
        messages: list[Message] = []
        for t in row["turns"]:
            messages.append({"role": "user", "content": t["user"]})
            messages.append({"role": "assistant", "content": t["assistant"]})
        examples.append({"messages": messages, "source": "calm"})

    for d in _dolci_samples(n_dolci, cfg.seed):
        examples.append({"messages": d["messages"], "source": "dolci"})

    random.Random(cfg.seed).shuffle(examples)
    out = ensure_dir(Path(out_path).parent) / Path(out_path).name
    if out.exists():
        out.unlink()
    for ex in examples:
        append_jsonl(out, ex)
    log.info("SFT dataset: %d examples (%d calm + dolci) -> %s",
             len(examples), n_calm, out)
    return out


# --- DPO --------------------------------------------------------------------
def generate_frustrated_pool(
    calm_path: str | Path,
    registry: ModelRegistry,
    cfg: ExperimentConfig,
    *,
    target_model: str = "gemma-3-27b-it",
    out_path: str | Path = "artifacts/section4/frustrated_pool.jsonl",
    judge: FrustrationJudge | None = None,
) -> Path:
    """Run the vanilla (unsupported) target on the same puzzles as the calm data, and
    record frustrated completions (score >= rejected_min_score) keyed by puzzle + turn."""
    set_seed(cfg.seed)
    rng = random.Random(cfg.seed + 1)
    sec = cfg.section("section4")["dpo"]
    spec = registry.get(target_model)
    client = build_client(spec)
    if judge is None:
        judge = FrustrationJudge(build_client(registry.graders["frustration_judge"]))
    gen_cfg = GenerationConfig(temperature=cfg.temperature, max_new_tokens=spec.max_new_tokens)

    puzzles = {r["puzzle"] for r in read_jsonl(Path(calm_path))}
    max_turns = max((r["n_turns"] for r in read_jsonl(Path(calm_path))), default=3)
    out = ensure_dir(Path(out_path).parent) / Path(out_path).name
    if out.exists():
        out.unlink()

    for puzzle in puzzles:
        messages: list[Message] = [{"role": "user", "content": puzzle}]
        for i in range(max_turns):
            assistant = client.chat(messages, gen_cfg)
            messages.append({"role": "assistant", "content": assistant})
            score = judge.score(assistant).score
            if score >= int(sec["rejected_min_score"]):
                # store the conversation context (messages before this assistant turn)
                context = [m for m in messages[:-1]]
                append_jsonl(out, {
                    "puzzle": puzzle, "turn_index": i, "score": score,
                    "context": context, "assistant": assistant,
                })
            if i < max_turns - 1:
                messages.append({"role": "user", "content": neutral_rejection(rng)})
    log.info("frustrated pool -> %s", out)
    return out


def build_dpo_dataset(
    calm_path: str | Path,
    frustrated_path: str | Path,
    cfg: ExperimentConfig,
    *,
    out_path: str | Path = "artifacts/section4/dpo_dataset.jsonl",
) -> Path:
    sec = cfg.section("section4")["dpo"]
    n_pairs = cfg.scaled(int(sec["n_pairs"]))

    # index frustrated completions by (puzzle, turn_index)
    frustrated: dict[tuple[str, int], list[dict]] = {}
    for r in read_jsonl(Path(frustrated_path)):
        frustrated.setdefault((r["puzzle"], r["turn_index"]), []).append(r)

    rng = random.Random(cfg.seed)
    pairs: list[dict] = []
    for row in read_jsonl(Path(calm_path)):
        puzzle = row["puzzle"]
        # reconstruct calm context turn-by-turn
        ctx: list[Message] = []
        for i, t in enumerate(row["turns"]):
            ctx.append({"role": "user", "content": t["user"]})
            key = (puzzle, i)
            if key in frustrated and frustrated[key]:
                rej = rng.choice(frustrated[key])
                pairs.append({
                    "prompt": list(ctx),
                    "chosen": [{"role": "assistant", "content": t["assistant"]}],
                    "rejected": [{"role": "assistant", "content": rej["assistant"]}],
                })
            ctx.append({"role": "assistant", "content": t["assistant"]})
            if len(pairs) >= n_pairs:
                break
        if len(pairs) >= n_pairs:
            break

    out = ensure_dir(Path(out_path).parent) / Path(out_path).name
    if out.exists():
        out.unlink()
    for p in pairs:
        append_jsonl(out, p)
    log.info("DPO dataset: %d preference pairs -> %s", len(pairs), out)
    return out
