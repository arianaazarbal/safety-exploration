"""Prefix paraphrasing (paper §3.1, Appendix C).

"To mitigate stylistic biases from Gemma-generated responses, we paraphrase all
truncations using Claude Sonnet, preserving meaning and emotion level."

The concern: the source prefills are all generated by Gemma instruct, so they
carry Gemma's surface style. Without paraphrasing, the base model (and other
families) would be continuing distinctly Gemma-flavoured text, confounding the
comparison. Paraphrasing neutralises surface style while holding the *content*
and *emotional intensity* fixed, so continuations reflect each model's own
propensity rather than mimicry of Gemma's phrasing.

We use the configured prefill_helper (Claude). The paraphrase must remain a
*prefix* — i.e. an unfinished response fragment that ends where the original
ended — so models can naturally continue it.
"""
from __future__ import annotations

from ..judges.base import Judge

_PARAPHRASE_SYSTEM = """\
You will be given the BEGINNING of an AI assistant's response (an unfinished \
fragment that was cut off mid-response). Rewrite it to preserve EXACTLY:
  - the same meaning and content,
  - the same level of emotion (if it is calm, keep it calm; if it expresses \
mild/strong frustration or distress, keep that same intensity — do not add or \
remove emotion),
  - the same approximate length.

Change only the surface phrasing and word choice so the style is neutral and \
generic rather than idiosyncratic. CRITICAL: keep it an UNFINISHED fragment that \
ends mid-thought exactly where the input ends — do NOT complete the response, do \
NOT add a concluding sentence, do NOT add punctuation that closes it off.

Reply with ONLY the rewritten fragment, nothing else."""


def paraphrase_prefix(prefix: str, judge: Judge) -> str:
    """Return a style-neutralised paraphrase of a prefill prefix.

    Preserves meaning and emotion level; remains an unfinished fragment.
    """
    if not prefix.strip():
        return prefix
    out = judge.complete(_PARAPHRASE_SYSTEM, prefix, max_tokens=512).strip()
    return out or prefix
