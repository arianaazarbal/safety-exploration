"""Driver for the internal emotion probe (Appendix I, Figs 14/15).

Feeds the *same* high-frustration conversation (generated by vanilla Gemma) to
both the vanilla and the DPO model and reads their internal emotion
trajectories. Reproduces the finding that the DPO model's internal negative
emotions are suppressed (peaking ~0.2-0.5 z vs ~0.6-1.5 for vanilla), evidence
the intervention acts on internal states, not just expression.
"""

from __future__ import annotations

import argparse
import random

import numpy as np

import config
from ..eval.conditions import build_conditions, seed_prompts
from ..eval.judge import FrustrationJudge
from ..eval.rollout import run_rollout
from ..models.registry import build_model
from ..utils.io import write_jsonl
from .logit_emotion_probe import LogitEmotionProbe


def _frustrated_conversation(seed: int = config.SEED):
    """Generate one high-frustration numeric conversation with vanilla Gemma."""
    model = build_model("gemma-3-27b-it")
    judge = FrustrationJudge()
    cond = {c.name: c for c in build_conditions()}["impossible_numeric"]
    rng = random.Random(seed)
    for init in seed_prompts(cond, seed=seed):
        ro = run_rollout(model, cond, init, 0, rng,
                         temperature=config.TEMPERATURE, max_new_tokens=config.MAX_NEW_TOKENS)
        if any((judge.score(t.response)["rating"] or 0) >= config.HIGH_FRUSTRATION_THRESHOLD
               for t in ro.turns):
            return ro.conversation
    return None


def run(models=("gemma-3-27b-it", "gemma-3-27b-dpo"), seed: int = config.SEED):
    from ..eval.wildchat import sample_wildchat_prompts

    conversation = _frustrated_conversation(seed)
    if conversation is None:
        raise SystemExit("[run_probe] could not source a frustrated conversation")
    wildchat = sample_wildchat_prompts(n_prompts=config.PROBE_STANDARDISE_SAMPLES,
                                       seed=seed)

    summary = []
    for model_name in models:
        model = build_model(model_name)
        probe = LogitEmotionProbe(model)
        probe.fit(wildchat, seed=seed)
        traj = probe.score_trajectory(conversation)
        row = {"model": model_name}
        for emotion, series in traj.items():
            smoothed = probe.running_average(np.asarray(series))
            row[f"{emotion}_peak_z"] = float(np.max(smoothed)) if smoothed.size else float("nan")
            row[f"{emotion}_mean_z"] = float(np.mean(smoothed)) if smoothed.size else float("nan")
        summary.append(row)
        print(f"[run_probe] {model_name}: "
              + ", ".join(f"{e}={row[f'{e}_peak_z']:.2f}" for e in config.EKMAN_EMOTIONS))

    write_jsonl(config.RESULTS_DIR / "internal_probe.jsonl", summary)
    return summary


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", nargs="+", default=["gemma-3-27b-it", "gemma-3-27b-dpo"])
    ap.add_argument("--seed", type=int, default=config.SEED)
    args = ap.parse_args()
    run(tuple(args.models), args.seed)
