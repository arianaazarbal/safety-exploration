"""Build the SFT dataset (Section 4.1): 650 calm responses (1-3 turn calm
conversations) mixed with 500 standard-instruct samples from Dolci-Instruct-SFT
to mitigate degeneration (Table 9: 1,150 samples total).

Output is TRL conversational SFT format: ``{"messages": [...]}`` per example.
The calm examples reuse the stripped (no-reassurance) conversations generated by
``generate_calm_data``; the Dolci mix-in is loaded from the configured hub ID
(see DESIGN.md, "Dataset identifiers", for the ID assumption).
"""
from __future__ import annotations

import os
import random
from typing import List, Optional

from .. import config
from ..utils.io import append_jsonl, read_jsonl


def _load_dolci(n: int, seed: int) -> List[dict]:
    try:
        from datasets import load_dataset
    except Exception:
        return []
    try:
        ds = load_dataset(config.DATASETS.dolci_instruct, split="train",
                          streaming=True)
    except Exception:
        return []
    rng = random.Random(seed)
    pool: List[dict] = []
    for i, row in enumerate(ds):
        if i >= max(5000, n * 20):
            break
        msgs = row.get("messages") or row.get("conversation")
        if msgs:
            pool.append({"messages": msgs})
    rng.shuffle(pool)
    return pool[:n]


def build_sft_dataset(
    *,
    calm_path: str,
    n_calm: int = config.SFT.n_calm,
    n_dolci: int = config.SFT.n_dolci,
    out_path: Optional[str] = None,
    seed: int = 0,
) -> str:
    config.PATHS.ensure()
    out_path = out_path or os.path.join(config.PATHS.training, "sft_data.jsonl")
    if os.path.exists(out_path):
        os.remove(out_path)

    rng = random.Random(seed)
    calm = [{"messages": rec["messages"]} for rec in read_jsonl(calm_path)]
    rng.shuffle(calm)
    calm = calm[:n_calm]

    dolci = _load_dolci(n_dolci, seed)
    if len(dolci) < n_dolci:
        # Document degraded run: fewer mix-in samples than the paper's 500.
        print(f"[build_sft_data] WARNING: only {len(dolci)} Dolci samples "
              f"available (requested {n_dolci}); see DESIGN.md.")

    examples = calm + dolci
    rng.shuffle(examples)
    for ex in examples:
        append_jsonl(out_path, ex)
    return out_path
