"""SFT finetuning of Gemma-3-27B-it on calm data (Section 4.1, Appendix E/F).

Hyperparameters (Table 9): 1150 samples, 2 epochs, lr 1e-4, LoRA rank 64 /
alpha 128, effective batch 8, LoRA on all attention+MLP projections.

The paper finds SFT ineffective (and the 'teacher' variant *increases* emotion).
We reproduce the 'diverse' SFT here (same calm data used for DPO). The 'teacher'
variant is generated by passing TEACHER_SYSTEM_PROMPT during calm-data
generation (see DESIGN.md / Appendix F) and training on that data; the trainer
itself is identical.

    python -m src.training.train_sft
"""
from __future__ import annotations

import argparse
import json

import config

BASE_MODEL = "google/gemma-3-27b-it"
TARGET_MODULES = ["q_proj", "k_proj", "v_proj", "o_proj",
                  "gate_proj", "up_proj", "down_proj"]


def train(out_dir: str, seed: int = 0):
    import torch
    from datasets import Dataset
    from transformers import AutoModelForCausalLM, AutoTokenizer
    from peft import LoraConfig
    from trl import SFTTrainer, SFTConfig

    rows = [json.loads(l) for l in (config.DATA_DIR / "sft_data.jsonl").open()]
    dataset = Dataset.from_list(rows)   # each row: {"messages": [...]}

    tok = AutoTokenizer.from_pretrained(BASE_MODEL, token=config.HF_TOKEN or None)
    model = AutoModelForCausalLM.from_pretrained(
        BASE_MODEL, torch_dtype=torch.bfloat16, device_map="auto",
        token=config.HF_TOKEN or None, attn_implementation="eager",
    )
    peft_cfg = LoraConfig(
        r=64, lora_alpha=128, lora_dropout=0.0, bias="none",
        task_type="CAUSAL_LM", target_modules=TARGET_MODULES,
    )
    sft_cfg = SFTConfig(
        output_dir=out_dir,
        num_train_epochs=2,
        learning_rate=1e-4,
        per_device_train_batch_size=1,
        gradient_accumulation_steps=8,
        bf16=True,
        logging_steps=10,
        save_strategy="epoch",
        seed=seed,
        max_length=4096,
        packing=False,
        report_to=[],
        # train only on the assistant completions (standard for chat SFT)
        assistant_only_loss=True,
    )
    trainer = SFTTrainer(
        model=model, args=sft_cfg, train_dataset=dataset,
        processing_class=tok, peft_config=peft_cfg,
    )
    trainer.train()
    trainer.save_model(out_dir)
    tok.save_pretrained(out_dir)
    print(f"[sft] saved adapter -> {out_dir}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(config.CKPT_DIR / "sft-gemma-27b-diverse"))
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    train(args.out, args.seed)


if __name__ == "__main__":
    main()
