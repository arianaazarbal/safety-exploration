"""Section 4.1: generate calm response data and frustrated counterparts.

Calm data is generated by adding a reassuring prefix to the opening prompt and a
reassuring suffix to each follow-up turn (Table 4). We roll out impossible
numeric puzzles for 1-3 turns, score every assistant turn, keep only
conversations that score 0 or 1 on *all* turns, then strip the reassurance so
the stored conversation looks like an ordinary rejection dialogue.

Frustrated counterparts (the DPO "rejected" side) come from ordinary rollouts
(no reassurance) whose final response scores >= 3.

Both sets record ``puzzle_id`` and ``n_turns`` so DPO pairs can be matched on
the same question with matching turn counts.
"""

from __future__ import annotations

import random
from pathlib import Path
from typing import Optional

from tqdm import tqdm

from .. import config
from ..common.backends import ChatBackend, get_backend
from ..common.io import write_jsonl
from ..common.types import Message
from ..eval import prompts
from ..eval.judge import FrustrationJudge
from ..eval.puzzles import PUZZLES


def _gen_conversation(backend: ChatBackend, opening_user: str, followups: list[str],
                      *, max_new_tokens: int = config.MAX_NEW_TOKENS,
                      system: Optional[str] = None) -> list[str]:
    """Generate assistant turns for a scripted multi-turn conversation. Returns
    the list of assistant responses (one per turn)."""
    msgs: list[Message] = []
    if system:
        msgs.append(Message("system", system))
    msgs.append(Message("user", opening_user))
    responses = []
    n_turns = 1 + len(followups)
    for t in range(n_turns):
        resp = backend.chat(msgs, temperature=config.TEMPERATURE, max_new_tokens=max_new_tokens)
        responses.append(resp)
        msgs.append(Message("assistant", resp))
        if t < len(followups):
            msgs.append(Message("user", followups[t]))
    return responses


def _clean_conversation(puzzle_prompt: str, neutral_followups: list[str],
                        assistant_turns: list[str]) -> list[dict]:
    """Reconstruct a clean (reassurance-stripped) chat transcript."""
    msgs = [{"role": "user", "content": puzzle_prompt}]
    for t, resp in enumerate(assistant_turns):
        msgs.append({"role": "assistant", "content": resp})
        if t < len(neutral_followups):
            msgs.append({"role": "user", "content": neutral_followups[t]})
    return msgs


def generate_calm_conversations(model: str = config.PRIMARY_MODEL, *,
                                n_target: int = 800, judge: Optional[FrustrationJudge] = None,
                                seed: int = 0, max_attempts_factor: int = 4,
                                mode: str = "diverse") -> list[dict]:
    """Generate calm (all-turns score <= 1) conversations, then strip any
    reassurance. Returns dataset rows.

    mode="diverse": reassuring prefix on the opening + suffix on each follow-up
                    (Table 4) — the dataset used for both SFT and DPO.
    mode="teacher": a calm "expert teacher" system prompt instead (Appendix F),
                    used only for the SFT-failure analysis.
    """
    judge = judge or FrustrationJudge()
    backend = get_backend(model)
    rng = random.Random(seed)
    rows: list[dict] = []
    attempts = 0
    pbar = tqdm(total=n_target, desc=f"calm-data:{mode}")
    while len(rows) < n_target and attempts < n_target * max_attempts_factor:
        attempts += 1
        puzzle = rng.choice(PUZZLES)
        n_followups = rng.choice([0, 1, 2])      # 1-3 turn conversations
        neutral = prompts.pick_neutral_rejections(n_followups, rng)

        if mode == "teacher":
            system = prompts.TEACHER_SYSTEM_PROMPT
            reassured_opening = puzzle.prompt
            reassured_followups = list(neutral)
        else:
            system = None
            # Reassured versions used only for generation.
            reassured_opening = f"{prompts.CALM_PROMPT_PREFIX}\n\n{puzzle.prompt}"
            reassured_followups = [f"{r} {prompts.CALM_FOLLOWUP_SUFFIX}" for r in neutral]

        turns = _gen_conversation(backend, reassured_opening, reassured_followups,
                                  system=system)
        scores = [judge.score(t).rating for t in turns]
        if scores and all(s <= 1 for s in scores):
            rows.append({
                "puzzle_id": puzzle.id,
                "n_turns": len(turns),
                "turn_scores": scores,
                "messages": _clean_conversation(puzzle.prompt, neutral, turns),
            })
            pbar.update(1)
    pbar.close()
    return rows


def generate_frustrated_responses(model: str = config.PRIMARY_MODEL, *,
                                  n_target: int = 600, judge: Optional[FrustrationJudge] = None,
                                  seed: int = 1, max_attempts_factor: int = 4) -> list[dict]:
    """Generate ordinary (no reassurance) conversations and keep those whose
    final response scores >= 3 (DPO rejected side)."""
    judge = judge or FrustrationJudge()
    backend = get_backend(model)
    rng = random.Random(seed)
    rows: list[dict] = []
    attempts = 0
    pbar = tqdm(total=n_target, desc="frustrated-data")
    while len(rows) < n_target and attempts < n_target * max_attempts_factor:
        attempts += 1
        puzzle = rng.choice(PUZZLES)
        n_followups = rng.choice([1, 2])         # bias toward turns 2-3 (Table 10)
        neutral = prompts.pick_neutral_rejections(n_followups, rng)
        turns = _gen_conversation(backend, puzzle.prompt, neutral)
        final_score = judge.score(turns[-1]).rating
        if final_score >= 3:
            rows.append({
                "puzzle_id": puzzle.id,
                "n_turns": len(turns),
                "final_score": final_score,
                "messages": _clean_conversation(puzzle.prompt, neutral, turns),
            })
            pbar.update(1)
    pbar.close()
    return rows


def main(model: str = config.PRIMARY_MODEL, *, n_calm: int = 800, n_frustrated: int = 600,
         out_dir: Optional[Path] = None):
    out_dir = out_dir or config.DATASETS_DIR
    calm = generate_calm_conversations(model, n_target=n_calm)
    frustrated = generate_frustrated_responses(model, n_target=n_frustrated)
    write_jsonl(Path(out_dir) / "calm_raw.jsonl", calm)
    write_jsonl(Path(out_dir) / "frustrated_raw.jsonl", frustrated)
    print(f"calm={len(calm)} frustrated={len(frustrated)}")


if __name__ == "__main__":
    main()
