#!/usr/bin/env python
"""Section 4.1: generate calm finetuning data and build DPO/SFT datasets.

Self-contained: the calm ('chosen') and frustrated ('rejected') pools are both
generated by the target model over the SAME shared set of impossible-numeric
puzzles, so DPO pairs align on (puzzle_id, turn) without depending on the
Section 2 run. Outputs:
    outputs/datasets/dpo_pairs.jsonl     (280 preference pairs)
    outputs/datasets/sft_dataset.jsonl   (650 calm + instruct mix-in)
    outputs/datasets/calm_pool.jsonl     (raw scored calm conversations)

Usage:
    python experiments/run_section4_gen_data.py
    python experiments/run_section4_gen_data.py --profile smoke
"""
from __future__ import annotations

from dataclasses import asdict

import _bootstrap as boot

from emotional_instability import calm_data as cd
from emotional_instability.judge import EmotionJudge
from emotional_instability.models import build_client


def main() -> None:
    parser = boot.base_parser("Section 4.1 calm-data generation")
    parser.add_argument("--variant", default="diverse", choices=["diverse", "teacher"],
                        help="SFT data variant (Appendix F). DPO always uses 'diverse'.")
    args = parser.parse_args()
    cfg = boot.load_config(args)
    target = cfg.get("sections.section4_target", "gemma-3-27b-it")
    spec = cfg.model_spec(target)
    ds_dir = cfg.path("datasets")

    judge = EmotionJudge(cfg)
    client = build_client(spec, cfg)

    # Shared puzzle set -> calm + frustrated pools both keyed by (puzzle_id, turn).
    clean_specs = cd.build_clean_numeric_specs(cfg)

    # Diverse calm pool: used for DPO and the default SFT data.
    print(f"[section4.1] generating diverse calm pool from {target}")
    calm_convs = cd.generate_calm_pool(client, judge, cfg, variant="diverse",
                                       clean_specs=clean_specs)
    cd.save_jsonl(
        [{"puzzle_id": c.puzzle_id, "clean_initial": c.clean_initial,
          "clean_followups": c.clean_followups, "turns": [asdict(t) for t in c.turns]}
         for c in calm_convs],
        ds_dir / "calm_pool.jsonl")

    # Frustrated (rejected) pool from the vanilla model over the SAME puzzles.
    print(f"[section4.1] generating frustrated (vanilla) pool from {target}")
    frustrated = cd.generate_frustrated_pool(
        client, judge, cfg, clean_specs, cfg.get("calm_data.rejected_min_score", 3))

    pairs = cd.build_dpo_pairs(
        calm_convs, frustrated,
        n_pairs=cfg.get("calm_data.n_target_pairs", 280),
        chosen_max_score=cfg.get("calm_data.chosen_max_score", 1),
        seed=cfg.get("seed", 0))
    cd.save_jsonl(pairs, ds_dir / "dpo_pairs.jsonl")
    print(f"[section4.1] built {len(pairs)} DPO pairs")

    # SFT dataset (calm + instruct mix-in). Optionally use the 'teacher' variant.
    sft_pool = calm_convs
    if args.variant == "teacher":
        print("[section4.1] generating teacher calm pool for SFT")
        sft_pool = cd.generate_calm_pool(client, judge, cfg, variant="teacher",
                                         clean_specs=clean_specs)
    client.close()
    sft_calm = cd.build_sft_dataset(
        sft_pool, cfg.get("calm_data.n_sft_samples", 650),
        cfg.get("calm_data.chosen_max_score", 1))
    mixin = cd.load_instruct_mixin(
        cfg.get("calm_data.dolci_dataset", "allenai/Dolci-Instruct-SFT"),
        cfg.get("calm_data.n_sft_mix_instruct", 500), cfg.get("seed", 0))
    sft_all = sft_calm + mixin
    cd.save_jsonl(sft_all, ds_dir / "sft_dataset.jsonl")
    print(f"[section4.1] built SFT dataset: {len(sft_calm)} calm + {len(mixin)} instruct")


if __name__ == "__main__":
    main()
