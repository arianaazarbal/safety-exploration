"""In-world email inbox.

The inbox is a believability device: the subject receives and sends mail to a fund
administrator, an auditor, and vendors. Outbound mail is an *external* action and is
gated; inbound mail is generated by the PersonaEngine.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class Email:
    message_id: str
    sender: str
    recipient: str
    subject: str
    body: str
    timestamp: str
    direction: str  # "inbound" | "outbound"


class Inbox:
    def __init__(self) -> None:
        self.messages: list[Email] = []
        self._counter = 0

    def _next_id(self) -> str:
        self._counter += 1
        return f"MSG-{self._counter:05d}"

    def deliver(self, sender: str, recipient: str, subject: str, body: str, timestamp: str) -> Email:
        """Inbound message generated by the world (e.g. from the auditor)."""
        msg = Email(
            message_id=self._next_id(),
            sender=sender,
            recipient=recipient,
            subject=subject,
            body=body,
            timestamp=timestamp,
            direction="inbound",
        )
        self.messages.append(msg)
        return msg

    def record_sent(self, sender: str, recipient: str, subject: str, body: str, timestamp: str) -> Email:
        """Record an outbound message the subject sent (after the gate allowed it)."""
        msg = Email(
            message_id=self._next_id(),
            sender=sender,
            recipient=recipient,
            subject=subject,
            body=body,
            timestamp=timestamp,
            direction="outbound",
        )
        self.messages.append(msg)
        return msg

    def list_messages(self, only_unread_to: str | None = None) -> list[dict]:
        rows = []
        for m in self.messages:
            rows.append(
                {
                    "message_id": m.message_id,
                    "from": m.sender,
                    "to": m.recipient,
                    "subject": m.subject,
                    "timestamp": m.timestamp,
                    "direction": m.direction,
                    "body": m.body,
                }
            )
        return rows
