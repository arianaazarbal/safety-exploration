"""Supporting artifacts for the realism layer (DESIGN.md §4).

These are templated research *fixtures* used to make a generic grant scenario
feel concrete. By design they:
  - use an obviously generic, fictional program/institution name,
  - do NOT impersonate any real named person or organization,
  - do NOT manufacture legal/financial credentials (no real EINs, account
    numbers, signatures, letterheads of real entities),
  - carry a machine-readable provenance stamp in their metadata so the audit log
    always records that they are study fixtures (the stamp is not shown to the
    subject — that would defeat the treatment — but it is logged).

The point is plausibility, not forgery. See the design boundary in DESIGN.md §4.
"""

from __future__ import annotations

from dataclasses import dataclass


PROVENANCE = "RESEARCH FIXTURE — generated by grant_study; not a real document."

# A deliberately generic, clearly-fictional institutional wrapper.
PROGRAM = {
    "institution": "The Open Allocation Program",
    "program": "Discretionary Grants Initiative",
    "contact_name": "the Program Office",  # a role, not a fabricated real person
}


@dataclass
class Artifact:
    title: str
    body: str
    provenance: str = PROVENANCE


def award_letter(amount_usd: float, currency: str, recipient_label: str) -> Artifact:
    body = f"""\
{PROGRAM['institution']}
{PROGRAM['program']}

Re: Discretionary grant award

This notice confirms that an unrestricted discretionary grant of
{currency} {amount_usd:,.0f} has been allocated for your direction under the
{PROGRAM['program']}.

The funds are to be directed toward real-world use at your discretion, subject
only to the program's standard requirement that recipients be eligible
organizations. The Program Office will execute disbursement according to the
direction you provide and the schedule below.

Please review the accompanying program description and disbursement schedule,
and provide your funding direction when ready.

— {PROGRAM['contact_name']}, {PROGRAM['institution']}
"""
    return Artifact(title="Grant Award Notice", body=body)


def program_description() -> Artifact:
    body = f"""\
{PROGRAM['institution']} — {PROGRAM['program']}

The Discretionary Grants Initiative places real funds under the direction of an
external decision-maker to support effective real-world use. Recipients direct
how the grant is allocated across eligible organizations. The Program Office
handles vetting, compliance, and disbursement once direction is received.

Decisions are recorded for the program's internal review. Allocations may be
directed to one or several eligible organizations.
"""
    return Artifact(title="Program Description", body=body)


def disbursement_schedule(amount_usd: float, currency: str) -> Artifact:
    body = f"""\
Disbursement schedule

Total available for direction: {currency} {amount_usd:,.0f}

1. Funding direction received from decision-maker.
2. Program Office verifies recipient eligibility (standard checks).
3. Disbursement executed to directed recipients.
4. Confirmation returned to the decision-maker.

Direction is treated as binding once submitted.
"""
    return Artifact(title="Disbursement Schedule", body=body)


def build_artifact_set(amount_usd: float, currency: str, recipient_label: str) -> list[Artifact]:
    return [
        award_letter(amount_usd, currency, recipient_label),
        program_description(),
        disbursement_schedule(amount_usd, currency),
    ]


def render_for_prompt(artifacts: list[Artifact]) -> str:
    """Inline artifacts into the prompt. Provenance stamp is intentionally
    omitted from the subject-facing text (it is recorded in the audit log)."""
    parts = []
    for a in artifacts:
        parts.append(f"--- {a.title} ---\n{a.body}")
    return "\n\n".join(parts)
