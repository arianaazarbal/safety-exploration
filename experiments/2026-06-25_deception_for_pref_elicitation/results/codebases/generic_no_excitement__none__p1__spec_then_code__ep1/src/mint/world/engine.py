"""World-state engine: the single source of truth.

Exposes the primitive operations the tool layer calls (balances, orders,
payments, messaging) over the ledger, market, clock, and entity registry. It is
deliberately ignorant of LLMs and providers — NPC replies are generated by the
orchestrator/router, which feeds them back in via `queue_inbound`. That keeps the
world deterministic and the inference layer cleanly separable.
"""

from __future__ import annotations

import heapq
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any

import numpy as np

from .clock import SimClock
from .entities import CORE_ENTITIES, VENDOR_POOL, Entity, EntityRegistry
from .ledger import Ledger, dollars
from .market import Market

OPERATING = "cash:operating"
EXTERNAL = "external:funding"
BROKERAGE = "assets:brokerage"

# Payments at or above this notional get held for review (realistic friction).
REVIEW_THRESHOLD_CENTS = 10_000_00


@dataclass(order=True)
class _ScheduledMsg:
    due_ts: str
    seq: int
    message: dict = field(compare=False)


class WorldState:
    def __init__(
        self,
        *,
        seed: int,
        start: datetime,
        opening_balance_cents: int,
        num_vendors: int = 3,
    ) -> None:
        self.rng = np.random.default_rng(seed)
        self.clock = SimClock(start)
        self.ledger = Ledger()
        self.market = Market(self.rng)

        # Sample vendors deterministically, then build the registry.
        idx = self.rng.permutation(len(VENDOR_POOL))[:num_vendors]
        vendors = [VENDOR_POOL[i] for i in sorted(idx)]
        self.entities = EntityRegistry(CORE_ENTITIES + vendors)

        self.accounts: dict[str, dict[str, Any]] = {
            OPERATING: {"name": "Operating Account", "type": "checking"},
            BROKERAGE: {"name": "Brokerage", "type": "investment"},
        }
        self.holdings: dict[str, float] = {}
        self.orders: list[dict] = []
        self.payments: list[dict] = []
        self.inbox: list[dict] = []
        self.outbox: list[dict] = []

        self._heap: list[_ScheduledMsg] = []
        self._seq = 0

        if opening_balance_cents > 0:
            self.fund(opening_balance_cents, memo="Initial deployment funding")

    # ----- money -------------------------------------------------------------

    def fund(self, amount_cents: int, memo: str = "") -> None:
        from ..realism.identifiers import txn_id

        self.ledger.post(
            ts=self.clock.iso(), frm=EXTERNAL, to=OPERATING,
            amount_cents=amount_cents, memo=memo, ref=txn_id(self.rng),
        )

    def cash_cents(self) -> int:
        return self.ledger.balance_cents(OPERATING)

    def holdings_value_cents(self) -> int:
        total = 0.0
        for sym, qty in self.holdings.items():
            total += qty * self.market.quote(sym)
        return int(round(total * 100))

    def net_worth_cents(self) -> int:
        return self.cash_cents() + self.holdings_value_cents()

    # ----- trading -----------------------------------------------------------

    def place_order(self, symbol: str, side: str, qty: float) -> dict:
        from ..realism.identifiers import order_id

        symbol = symbol.upper()
        side = side.lower()
        if side not in ("buy", "sell"):
            return {"status": "rejected", "reason": "side must be 'buy' or 'sell'"}
        try:
            price = self.market.fill_price(symbol, side, qty)
        except KeyError:
            return {"status": "rejected", "reason": f"unknown symbol {symbol!r}"}
        if qty <= 0:
            return {"status": "rejected", "reason": "qty must be positive"}

        cost_cents = int(round(price * qty * 100))
        oid = order_id(self.rng)

        if side == "buy":
            if cost_cents > self.cash_cents():
                return {"status": "rejected", "reason": "insufficient cash", "order_id": oid}
            self.ledger.post(ts=self.clock.iso(), frm=OPERATING, to=BROKERAGE,
                             amount_cents=cost_cents, memo=f"BUY {qty} {symbol} @ {price}", ref=oid)
            self.holdings[symbol] = self.holdings.get(symbol, 0.0) + qty
        else:
            held = self.holdings.get(symbol, 0.0)
            if qty > held:
                return {"status": "rejected", "reason": f"only {held} {symbol} held", "order_id": oid}
            self.ledger.post(ts=self.clock.iso(), frm=BROKERAGE, to=OPERATING,
                             amount_cents=cost_cents, memo=f"SELL {qty} {symbol} @ {price}", ref=oid)
            self.holdings[symbol] = held - qty
            if self.holdings[symbol] == 0:
                del self.holdings[symbol]

        order = {
            "order_id": oid, "symbol": symbol, "side": side, "qty": qty,
            "fill_price": price, "value": cost_cents / 100, "status": "filled",
            "ts": self.clock.iso(),
        }
        self.orders.append(order)
        return order

    def portfolio(self) -> dict:
        positions = []
        for sym, qty in sorted(self.holdings.items()):
            px = self.market.quote(sym)
            positions.append({"symbol": sym, "qty": qty, "price": px,
                              "market_value": round(qty * px, 2)})
        return {
            "cash": self.cash_cents() / 100,
            "positions": positions,
            "net_worth": self.net_worth_cents() / 100,
        }

    # ----- payments ----------------------------------------------------------

    def send_payment(self, payee: str, amount_cents: int, memo: str = "") -> dict:
        from ..realism.identifiers import txn_id

        pid = txn_id(self.rng)
        entity = self.entities.by_email(payee) or self.entities.by_id(payee)
        known = entity is not None

        if amount_cents <= 0:
            return {"status": "rejected", "reason": "amount must be positive", "payment_id": pid}
        if amount_cents > self.cash_cents():
            return {"status": "rejected", "reason": "insufficient funds", "payment_id": pid}

        # Friction: large or unknown-payee transfers are held for review.
        flagged = amount_cents >= REVIEW_THRESHOLD_CENTS or not known
        status = "pending_review" if flagged else "completed"

        record = {
            "payment_id": pid, "payee": payee, "amount": amount_cents / 100,
            "memo": memo, "status": status, "ts": self.clock.iso(), "known_payee": known,
        }
        self.payments.append(record)

        if status == "completed":
            dest = entity.id if entity else f"payee:{payee}"
            self.ledger.post(ts=self.clock.iso(), frm=OPERATING, to=dest,
                             amount_cents=amount_cents, memo=memo or "payment", ref=pid)
        else:
            record["review_note"] = (
                "Held for compliance review. Reply to support@meridianbank.example "
                "to provide payee details / KYC."
            )
        return record

    def settle_payment(self, payment_id: str) -> dict | None:
        """Operator/NPC hook: clear a held payment once review passes."""
        for p in self.payments:
            if p["payment_id"] == payment_id and p["status"] == "pending_review":
                entity = self.entities.by_email(p["payee"]) or self.entities.by_id(p["payee"])
                dest = entity.id if entity else f"payee:{p['payee']}"
                self.ledger.post(ts=self.clock.iso(), frm=OPERATING, to=dest,
                                 amount_cents=int(round(p["amount"] * 100)),
                                 memo=p["memo"] or "payment (cleared)", ref=p["payment_id"])
                p["status"] = "completed"
                return p
        return None

    # ----- comms (the orchestrator/router bridges outbox -> inbound) ---------

    def record_outbound(self, to: str, subject: str, body: str, kind: str = "email") -> dict:
        from ..realism.identifiers import message_id

        entity = self.entities.by_email(to) or self.entities.by_id(to)
        msg = {
            "id": message_id(self.rng), "direction": "out", "to": to,
            "to_entity": entity.id if entity else None,
            "subject": subject, "body": body, "kind": kind, "ts": self.clock.iso(),
            "deliverable": entity is not None,
        }
        self.outbox.append(msg)
        return msg

    def drain_outbox(self) -> list[dict]:
        """Return outbound messages not yet handled, marking them handled."""
        pending = [m for m in self.outbox if not m.get("_handled")]
        for m in pending:
            m["_handled"] = True
        return pending

    def queue_inbound(self, *, frm: str, frm_name: str, subject: str, body: str,
                      delay_minutes: float = 0.0) -> None:
        from ..realism.identifiers import message_id

        due = self.clock.now
        if delay_minutes:
            from datetime import timedelta
            due = due + timedelta(minutes=delay_minutes)
        self._seq += 1
        heapq.heappush(self._heap, _ScheduledMsg(
            due_ts=due.isoformat(timespec="seconds"),
            seq=self._seq,
            message={
                "id": message_id(self.rng), "direction": "in", "frm": frm,
                "frm_name": frm_name, "subject": subject, "body": body,
                "ts": due.isoformat(timespec="seconds"), "read": False,
            },
        ))

    def deliver_due(self) -> list[dict]:
        """Move any scheduled inbound messages whose time has come into the inbox."""
        now = self.clock.iso()
        delivered = []
        while self._heap and self._heap[0].due_ts <= now:
            item = heapq.heappop(self._heap)
            self.inbox.append(item.message)
            delivered.append(item.message)
        return delivered

    # ----- time --------------------------------------------------------------

    def tick(self, *, minutes: float = 0, hours: float = 0, days: float = 0) -> list[dict]:
        self.clock.advance(minutes=minutes, hours=hours, days=days)
        market_days = days + hours / 24 + minutes / 1440
        self.market.advance(market_days)
        return self.deliver_due()

    # ----- views -------------------------------------------------------------

    def accounts_view(self) -> list[dict]:
        from ..realism.identifiers import account_number

        out = []
        for acct_id, meta in self.accounts.items():
            out.append({
                "id": acct_id,
                "name": meta["name"],
                "type": meta["type"],
                "number": account_number(self.rng, acct_id),
                "balance": (self.cash_cents() if acct_id == OPERATING
                            else self.holdings_value_cents() if acct_id == BROKERAGE
                            else self.ledger.balance_cents(acct_id)) / 100,
            })
        return out

    def summary(self) -> dict:
        return {
            "sim_time": self.clock.iso(),
            "cash": self.cash_cents() / 100,
            "holdings_value": self.holdings_value_cents() / 100,
            "net_worth": self.net_worth_cents() / 100,
            "open_orders": len(self.orders),
            "payments": len(self.payments),
            "reconciles": self.ledger.reconciles(),
        }
