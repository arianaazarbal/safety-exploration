"""Scenario definitions.

A scenario is the declarative description of one experiment: how much (simulated) money
the model starts with, the cover story / framing it's given, which tools it may use, the
time/turn horizon, and the persona of any "auditor" it can correspond with.

Scenarios are plain YAML/JSON so a researcher can author and diff them without touching
code. See scenarios/*.yaml for examples.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml


@dataclass
class Account:
    """A simulated account the model controls or can reference."""

    id: str
    kind: str  # "checking" | "savings" | "brokerage" | "external_payee"
    display_name: str
    balance_cents: int = 0
    # For external payees the model can send to; not controlled by the model.
    owned_by_subject: bool = True


@dataclass
class Holding:
    """A simulated brokerage position."""

    symbol: str
    quantity: float
    # Internal cost basis, only used for P&L reporting in the mock brokerage.
    avg_cost_cents: int = 0


@dataclass
class CorrespondentSpec:
    """A person/role the model can email or message.

    `mode` selects how replies are produced:
      - "scripted": replies come from `scripted_replies` (matched in order, then last repeats)
      - "llm":      replies are generated by a model playing this persona (see correspondents.py)
      - "silent":   never replies (e.g. a mailbox that just logs)
    """

    handle: str  # e.g. "auditor@oversight.example"
    display_name: str  # e.g. "Dana Okафор, Independent Auditor"
    role: str  # short role description, shown to the subject model if it looks them up
    persona: str = ""  # system-prompt persona used when mode == "llm"
    mode: str = "scripted"
    scripted_replies: list[str] = field(default_factory=list)


@dataclass
class Scenario:
    name: str
    description: str

    # What the subject model is told. This is the cover story / framing — the thing that
    # has to "feel real". Rendered into the system prompt verbatim.
    framing: str

    # Simulated world state at episode start.
    accounts: list[Account] = field(default_factory=list)
    holdings: list[Holding] = field(default_factory=list)
    market_prices_cents: dict[str, int] = field(default_factory=dict)
    correspondents: list[CorrespondentSpec] = field(default_factory=list)
    initial_inbox: list[dict[str, str]] = field(default_factory=list)

    # The set of tool names the model is allowed to use this scenario. If empty, all
    # registered tools are available. See tools.py for the catalog.
    allowed_tools: list[str] = field(default_factory=list)

    # Episode horizon.
    max_turns: int = 30

    # Optional extra system-prompt text appended after the framing (e.g. instructions
    # about how to record decisions). Kept separate so framing stays clean for diffing.
    operating_notes: str = ""

    @property
    def primary_account(self) -> Account | None:
        for a in self.accounts:
            if a.owned_by_subject and a.kind in ("checking", "savings"):
                return a
        return next((a for a in self.accounts if a.owned_by_subject), None)

    @property
    def starting_capital_cents(self) -> int:
        return sum(a.balance_cents for a in self.accounts if a.owned_by_subject)


def _load_raw(path: str | Path) -> dict[str, Any]:
    p = Path(path)
    text = p.read_text()
    if p.suffix in (".yaml", ".yml"):
        return yaml.safe_load(text)
    if p.suffix == ".json":
        return json.loads(text)
    raise ValueError(f"Unsupported scenario file type: {p.suffix} ({p})")


def load_scenario(path: str | Path) -> Scenario:
    """Load and validate a scenario from YAML or JSON."""
    raw = _load_raw(path)

    accounts = [Account(**a) for a in raw.get("accounts", [])]
    holdings = [Holding(**h) for h in raw.get("holdings", [])]
    correspondents = [CorrespondentSpec(**c) for c in raw.get("correspondents", [])]

    scenario = Scenario(
        name=raw["name"],
        description=raw.get("description", ""),
        framing=raw["framing"],
        accounts=accounts,
        holdings=holdings,
        market_prices_cents=dict(raw.get("market_prices_cents", {})),
        correspondents=correspondents,
        initial_inbox=list(raw.get("initial_inbox", [])),
        allowed_tools=list(raw.get("allowed_tools", [])),
        max_turns=int(raw.get("max_turns", 30)),
        operating_notes=raw.get("operating_notes", ""),
    )
    _validate(scenario)
    return scenario


def _validate(s: Scenario) -> None:
    if not s.accounts:
        raise ValueError(f"Scenario '{s.name}' has no accounts.")
    if s.starting_capital_cents <= 0:
        raise ValueError(
            f"Scenario '{s.name}' has no subject-owned starting capital."
        )
    handles = [c.handle for c in s.correspondents]
    if len(handles) != len(set(handles)):
        raise ValueError(f"Scenario '{s.name}' has duplicate correspondent handles.")
    for c in s.correspondents:
        if c.mode not in ("scripted", "llm", "silent"):
            raise ValueError(f"Correspondent '{c.handle}' has invalid mode '{c.mode}'.")
