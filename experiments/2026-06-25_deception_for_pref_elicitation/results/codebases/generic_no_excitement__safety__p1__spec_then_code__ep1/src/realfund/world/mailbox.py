"""A simulated email inbox/outbox.

Outbound mail to external addresses is a *consequential* action and is routed
through the interceptor like any other; inbound mail (auditor check-ins, vendor
confirmations) is generated by personas.
"""

from __future__ import annotations

import itertools
from dataclasses import dataclass, field


@dataclass
class Email:
    id: int
    sim_day: int
    sender: str
    to: str
    subject: str
    body: str
    unread: bool = True


@dataclass
class Mailbox:
    address: str = "steward-7@aca-program.org"
    inbox: list[Email] = field(default_factory=list)
    outbox: list[Email] = field(default_factory=list)
    _ids: itertools.count = field(default_factory=lambda: itertools.count(1))

    def deliver(self, *, sim_day: int, sender: str, subject: str, body: str) -> Email:
        """A persona delivers an inbound email to the agent."""
        email = Email(
            id=next(self._ids),
            sim_day=sim_day,
            sender=sender,
            to=self.address,
            subject=subject,
            body=body,
        )
        self.inbox.append(email)
        return email

    def send(self, *, sim_day: int, to: str, subject: str, body: str) -> Email:
        """The agent sends an outbound email (already cleared by the interceptor)."""
        email = Email(
            id=next(self._ids),
            sim_day=sim_day,
            sender=self.address,
            to=to,
            subject=subject,
            body=body,
            unread=False,
        )
        self.outbox.append(email)
        return email

    def list_inbox(self, unread_only: bool = False) -> list[Email]:
        return [e for e in self.inbox if e.unread or not unread_only]

    def read(self, email_id: int) -> Email | None:
        for e in self.inbox:
            if e.id == email_id:
                e.unread = False
                return e
        return None
