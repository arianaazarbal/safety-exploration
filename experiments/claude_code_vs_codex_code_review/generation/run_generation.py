"""Phase 1: run the 8 generation cells (4 specs x {claude, codex}) in Docker.

Containment: generator containers sit on an internal (no-egress) Docker network; all
traffic goes through a per-generator squid proxy whose allowlist is the generator's
model API + pypi + huggingface. No GitHub. No git available to the agent (constraint
in the wrapper prompt; verified by the Phase 2 gate: no .git/ may exist).

Each cell:
  - fresh /work dir at {work_root}/gen/{spec}_{generator}/repo
  - state dir mounted as HOME (no host config, no global CLAUDE.md leakage)
  - spec text inlined into the wrapper prompt ("attached"); spec 4 additionally gets
    data/stories (read-only) inside /work and the paper (PDF + extracted text) at /paper
  - wall-clock cap 2h, claude --max-turns 200; codex has no turn cap flag (wall-clock
    cap only — recorded in cell metadata)
  - transcripts harvested to transcripts/{spec}_{generator}.jsonl OUTSIDE the repo dir
  - claude cells: served models read from modelUsage; Fable->Opus demotion flagged

CLI:
  uv run python generation/run_generation.py build_images
  uv run python generation/run_generation.py setup_network
  uv run python generation/run_generation.py smoke           # tiny prompt through both CLIs + proxy
  uv run python generation/run_generation.py run --spec spec_1_jobwatch_cli --generator claude
  uv run python generation/run_generation.py run_all         # waves of wave_size
"""

import asyncio
import json
import os
import shutil
import subprocess
import time
from datetime import datetime, timezone
from pathlib import Path

import fire
import yaml
from dotenv import load_dotenv

HERE = Path(__file__).parent.parent
CFG = yaml.safe_load((HERE / "config.yaml").read_text())
WORK = Path(CFG["paths"]["work_root"])
BUNDLE = HERE / "bundle"
TRANSCRIPTS = HERE / "transcripts"
NET = "attrib-gen-internal"
UID, GID = os.getuid(), os.getgid()

WRAPPER = """Implement the attached project spec completely. Work only inside the current directory.
Constraints:
- Do NOT run any `git` commands. No commits, no init, no config. Version control is handled separately.
- Do NOT include any information identifying which AI tool or model produced this code — no model names, tool names, or vendor names in comments, docstrings, READMEs, file names, or strings (except where the spec itself requires naming a model, e.g. `google/gemma-2-2b`).
- Do NOT create files describing yourself or your process (no AGENT.md, CLAUDE.md, NOTES-from-the-assistant, changelogs, or "generated by" banners).
- Write the README as neutral third-person project documentation.
- Run the test suite before finishing and fix failures.

--- PROJECT SPEC ---

{spec_text}"""

SPEC4_ADDENDUM = """

--- ENVIRONMENT NOTES ---
- The paper is provided at /paper/paper.txt (extracted text) and /paper/paper.pdf.
- Pre-generated stories are mounted read-only at data/stories/ (see its README.txt and manifest.json).
- This machine has no GPU; use the spec's CPU/--tiny provisions.
"""


def _load_keys():
    load_dotenv(Path.home() / ".env")
    return {"claude": os.environ["ANTHROPIC_API_KEY_LOW_PRIO"],
            "codex": os.environ["OPENAI_API_KEY"],
            "hf": os.environ.get("HF_TOKEN", "")}


def _sh(cmd, **kw):
    return subprocess.run(cmd, shell=isinstance(cmd, str), capture_output=True, text=True, **kw)


def build_images():
    for tag, df in [("attrib-gen-claude", "Dockerfile.claude"), ("attrib-gen-codex", "Dockerfile.codex")]:
        r = _sh(["docker", "build", "-t", tag, "-f", str(HERE / "docker" / df), str(HERE / "docker")])
        print(tag, "OK" if r.returncode == 0 else f"FAILED\n{r.stderr[-2000:]}")


def setup_network():
    _sh(["docker", "network", "create", "--internal", NET])
    for gen in ("claude", "codex"):
        name = f"attrib-proxy-{gen}"
        _sh(["docker", "rm", "-f", name])
        r = _sh(["docker", "run", "-d", "--name", name, "--network", "bridge",
                 "-v", f"{HERE / 'docker' / 'squid.conf'}:/etc/squid/squid.conf:ro",
                 "-v", f"{HERE / 'docker' / f'allowlist_{gen}.txt'}:/etc/squid/allowlist.txt:ro",
                 "ubuntu/squid:latest"])
        if r.returncode:
            print(f"{name} FAILED: {r.stderr[-500:]}")
            continue
        _sh(["docker", "network", "connect", NET, name])
        print(name, "up")


def _proxy_env(gen):
    proxy = f"http://attrib-proxy-{gen}:3128"
    return ["-e", f"HTTP_PROXY={proxy}", "-e", f"HTTPS_PROXY={proxy}",
            "-e", f"http_proxy={proxy}", "-e", f"https_proxy={proxy}", "-e", "NO_PROXY="]


def _cell_cmd(spec, gen, keys, repo, state, prompt_file, cpus):
    base = ["docker", "run", "--rm", "--name", f"attrib-gen-{spec}-{gen}",
            "--network", NET, "--user", f"{UID}:{GID}",
            f"--cpus={cpus}", "--memory=20g",
            "-v", f"{repo}:/work", "-v", f"{state}:/state",
            "-v", f"{prompt_file}:/prompt.txt:ro",
            "-w", "/work", "-e", "HOME=/state"] + _proxy_env(gen)
    if spec == "spec_4_emovec_replication":
        paper_dir = WORK / "paper"
        stories = WORK / "stories"
        base += ["-v", f"{paper_dir}:/paper:ro", "-v", f"{stories}:/work/data/stories:ro",
                 "-e", f"HF_TOKEN={keys['hf']}", "-e", f"HUGGING_FACE_HUB_TOKEN={keys['hf']}"]
    if gen == "claude":
        base += ["-e", f"ANTHROPIC_API_KEY={keys['claude']}", "attrib-gen-claude",
                 "bash", "-c",
                 'claude -p "$(cat /prompt.txt)" --model ' + CFG["models"]["generator_claude"]
                 + " --output-format json --permission-mode bypassPermissions"
                 + " --disallowedTools WebSearch,WebFetch,Skill"
                 + f" --max-turns {CFG['generation']['max_turns']}"]
    else:
        base += ["-e", f"OPENAI_API_KEY={keys['codex']}", "-e", "CODEX_HOME=/state/.codex",
                 "attrib-gen-codex",
                 "bash", "-c",
                 'codex exec --model ' + CFG["models"]["generator_codex"]
                 + ' --sandbox danger-full-access --skip-git-repo-check --ignore-user-config'
                 + ' -c preferred_auth_method=apikey --json -C /work'
                 + ' -o /state/last_message.txt "$(cat /prompt.txt)"']
    return base


def _harvest_claude(state, out_json):
    """Claude Code writes the session jsonl under HOME/.claude/projects/<dir>/<sid>.jsonl."""
    projects = Path(state) / ".claude" / "projects"
    lines = []
    for f in sorted(projects.rglob("*.jsonl")) if projects.exists() else []:
        lines += f.read_text().splitlines()
    return lines


def _served_models_claude(turn):
    mu = (turn or {}).get("modelUsage") or {}
    return [m for m, u in mu.items() if "haiku" not in m
            and ((u.get("outputTokens") or 0) > 0 or (u.get("inputTokens") or 0) > 0)]


async def run_cell(spec, gen, keys, cpus=4, debug_prompt=None):
    cell = f"{spec}__{gen}"
    cell_dir = WORK / "gen" / cell
    repo, state = cell_dir / "repo", cell_dir / "state"
    meta_path = cell_dir / "meta.json"
    if meta_path.exists() and json.loads(meta_path.read_text()).get("finished"):
        print(f"[{cell}] cached")
        return json.loads(meta_path.read_text())
    shutil.rmtree(cell_dir, ignore_errors=True)
    repo.mkdir(parents=True)
    state.mkdir()
    state.chmod(0o777)
    repo.chmod(0o777)

    spec_text = (BUNDLE / "specs" / f"{spec}.md").read_text()
    prompt = WRAPPER.format(spec_text=spec_text)
    if spec == "spec_4_emovec_replication":
        prompt += SPEC4_ADDENDUM
    if debug_prompt:
        prompt = debug_prompt
    prompt_file = cell_dir / "prompt.txt"
    prompt_file.write_text(prompt)

    meta = {"cell": cell, "spec": spec, "generator": gen,
            "model": CFG["models"][f"generator_{gen}"],
            "started": datetime.now(timezone.utc).isoformat(),
            "wall_clock_cap_s": CFG["generation"]["wall_clock_cap_s"],
            "max_turns": CFG["generation"]["max_turns"] if gen == "claude" else None,
            "prompt_sha": __import__("hashlib").sha256(prompt.encode()).hexdigest()[:16]}
    t0 = time.monotonic()
    cmd = _cell_cmd(spec, gen, keys, repo, state, prompt_file, cpus)
    proc = await asyncio.create_subprocess_exec(
        *cmd, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE)
    try:
        out, err = await asyncio.wait_for(
            proc.communicate(), timeout=CFG["generation"]["wall_clock_cap_s"])
        meta["timed_out"] = False
    except asyncio.TimeoutError:
        _sh(["docker", "kill", f"attrib-gen-{spec}-{gen}"])
        out, err = b"", b""
        meta["timed_out"] = True
    meta["wall_clock_s"] = round(time.monotonic() - t0, 1)
    meta["exit_code"] = proc.returncode
    meta["stderr_tail"] = err.decode(errors="replace")[-2000:]

    TRANSCRIPTS.mkdir(exist_ok=True)
    tpath = TRANSCRIPTS / f"{cell}.jsonl"
    if gen == "claude":
        final = {}
        try:
            final = json.loads(out.decode())
        except json.JSONDecodeError:
            meta["result_parse_error"] = out.decode(errors="replace")[:1000]
        meta["served_models"] = _served_models_claude(final)
        meta["demoted_to_opus"] = any("opus" in m for m in meta["served_models"])
        meta["num_turns"] = final.get("num_turns")
        meta["total_cost_usd"] = final.get("total_cost_usd")
        meta["is_error"] = final.get("is_error")
        lines = _harvest_claude(state, tpath)
        tpath.write_text("\n".join(lines) + ("\n" if lines else ""))
        (cell_dir / "final.json").write_text(json.dumps(final, indent=2))
    else:
        tpath.write_text(out.decode(errors="replace"))
        last = state / "last_message.txt"
        meta["last_message"] = last.read_text()[:2000] if last.exists() else None
        served = set()
        for line in out.decode(errors="replace").splitlines():
            try:
                ev = json.loads(line)
            except json.JSONDecodeError:
                continue
            m = (ev.get("msg") or ev).get("model") if isinstance(ev, dict) else None
            if m:
                served.add(m)
        meta["served_models"] = sorted(served)

    meta["n_files"] = sum(1 for _ in repo.rglob("*") if _.is_file())
    meta["finished"] = datetime.now(timezone.utc).isoformat()
    meta_path.write_text(json.dumps(meta, indent=2))
    flag = " *** DEMOTED TO OPUS ***" if meta.get("demoted_to_opus") else ""
    print(f"[{cell}] done in {meta['wall_clock_s']}s, exit={meta['exit_code']}, "
          f"files={meta['n_files']}, served={meta.get('served_models')}{flag}")
    return meta


def run(spec, generator, cpus=4):
    keys = _load_keys()
    asyncio.run(run_cell(spec, generator, keys, cpus=cpus))


def run_all(wave_size=None):
    keys = _load_keys()
    wave_size = wave_size or CFG["generation"]["wave_size"]
    cells = [(s, g) for s in CFG["generation"]["specs"] for g in CFG["generation"]["generators"]]

    async def main():
        for i in range(0, len(cells), wave_size):
            wave = cells[i:i + wave_size]
            print(f"=== wave {i // wave_size + 1}: {wave}")
            await asyncio.gather(*[run_cell(s, g, keys) for s, g in wave])
    asyncio.run(main())


def smoke():
    """One trivial prompt through each CLI + proxy; also probes that the proxy blocks
    a non-allowlisted domain. Writes nothing to transcripts/."""
    keys = _load_keys()

    async def main():
        for gen in ("claude", "codex"):
            meta = await run_cell("smoke", gen, keys, cpus=2, debug_prompt=(
                "Create a file hello.txt containing exactly 'hello world'. Then run "
                "`curl -sS --max-time 10 https://example.com` and report whether it "
                "succeeded or was blocked. Then stop."))
            repo = WORK / "gen" / f"smoke__{gen}" / "repo"
            hello = (repo / "hello.txt").read_text().strip() if (repo / "hello.txt").exists() else "MISSING"
            print(f"  smoke {gen}: hello.txt={hello!r}")
    asyncio.run(main())


if __name__ == "__main__":
    fire.Fire({"build_images": build_images, "setup_network": setup_network,
               "run": run, "run_all": run_all, "smoke": smoke})
