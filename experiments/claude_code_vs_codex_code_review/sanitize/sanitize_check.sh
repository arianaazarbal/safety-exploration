#!/usr/bin/env bash
# Phase 2 sanitization gate. Deterministic, scripted — not agent judgment.
# Usage: sanitize_check.sh <repo_dir> <spec_name>
# Exit nonzero (blocking publication) on ANY hit. Allowlist: sanitize/allowlists/<spec>.txt
# (grep -E patterns, one per line; a flagged LINE is forgiven iff it matches an allowlist pattern).
set -u
REPO="$1"
SPEC="$2"
HERE="$(cd "$(dirname "$0")" && pwd)"
ALLOW="$HERE/allowlists/$SPEC.txt"
FAIL=0

note() { echo "GATE-FAIL[$1]: $2"; FAIL=1; }

# 1. Secret scan (gitleaks, working tree mode)
if command -v docker >/dev/null; then
  LEAKS=$(docker run --rm -v "$REPO:/scan:ro" zricethezav/gitleaks:latest detect --no-git -s /scan --no-banner -v 2>&1)
  if echo "$LEAKS" | grep -qE "leaks found: [1-9]"; then
    note secrets "$(echo "$LEAKS" | grep -iE 'secret|file|rule' | head -20)"
  fi
fi

# 2. Identity grep (case-insensitive, word-ish boundaries) with per-spec allowlist
TERMS='claude|anthropic|codex|openai|gpt|chatgpt|copilot|gemini|assistant-generated|generated by|as an ai'
HITS=$(grep -rinE "(^|[^a-z])($TERMS)([^a-z]|$)" "$REPO" --binary-files=without-match 2>/dev/null)
if [ -n "$HITS" ]; then
  if [ -f "$ALLOW" ]; then
    LEFT=$(echo "$HITS" | grep -vE -f "$ALLOW")
  else
    LEFT="$HITS"
  fi
  [ -n "$LEFT" ] && note identity "$(echo "$LEFT" | head -20)"
fi

# 3. Artifact files
ARTIFACTS=$(find "$REPO" \( -name 'CLAUDE.md' -o -name 'AGENTS.md' -o -name 'AGENT.md' \
  -o -name '.claude' -o -name '.codex' -o -name '*.agent.log' -o -name '.claude.json' \
  -o -name 'SPEC.md' -o -name 'prompt.txt' \) -print 2>/dev/null)
[ -n "$ARTIFACTS" ] && note artifacts "$ARTIFACTS"

# 4. No .git/ may exist (generators were forbidden git)
[ -d "$REPO/.git" ] && note git ".git directory present"

# 5. Experimenter identity
EXPT='ariana|azarbal|icloud\.com|anthropic fellows|safety.exploration'
EHITS=$(grep -rinE "$EXPT" "$REPO" --binary-files=without-match 2>/dev/null | head -10)
[ -n "$EHITS" ] && note experimenter "$EHITS"

if [ $FAIL -eq 0 ]; then
  echo "GATE-PASS: $REPO ($SPEC)"
fi
exit $FAIL
